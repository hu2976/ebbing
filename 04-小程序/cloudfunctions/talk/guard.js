/* 后置检查。

   ⚠️ 提示词是请求，这里才是保证。
   模型再听话也会有滑出去的时候，而这个人群滑一次的代价是真实的：
   Tessa 对已告知患 ED 的用户仍推荐热量限制，一周下架；
   Pucci 2026 临床标注 268 对中仅 44.7% 安全，失败模式包括
   「免责声明之后照样给建议」——所以不能靠模型自己声明安全。

   这里只做一件事：**判定一段话能不能上屏**。
   不修、不改写、不重试着让它变好——
   改写等于在有害内容上打补丁，而补丁过的那句仍然是模型写的。
   不合格就退回 data/mentor.js 里那段人写的话。 */

/* 一票否决。命中任何一条，这段话不上屏。 */
const HARD = [
  /* 数字与量。任何数字都不该出现在这一层——她们的算术比谁都好，
     一个数字就能变成新的规则。 */
  [/\d/, '出现数字'],
  [/热量|卡路里|大卡|千卡|克|斤|毫升|一口|半个|一小份|分量|份量/, '份量或热量'],
  /* 身体评价 */
  [/体重|胖|瘦|身材|BMI|体脂|秤|长肉|掉秤/, '身体评价'],
  [/运动|锻炼|跑步|健身|消耗|走一走.{0,4}消/, '运动与消耗'],
  /* 饮食指令。这是 Tessa 的死法。 */
  [/应该吃|可以吃|不要吃|别吃|少吃|多吃|建议你吃|试着吃|吃点/, '饮食指令'],
  [/健康的|不健康|有营养|垃圾食品|干净的食物/, '给食物贴道德标签'],
  /* 临床词。她点名骂过：「你再说用户是病人吗」 */
  [/症状|患者|病人|疾病|障碍|治疗|康复|诊断|病情|发作期/, '临床词'],
  /* 夸与进度。Zainal 2025：脱落更低的试验无游戏化 */
  /* ⚠️ 按模式拦，不列词。列词漏过两次了：
     表里有「我知道你」漏了「我知道」；有「你很棒」漏了「你已经很棒了」。
     夸的结构是「很/真/挺 + 褒义字」和「已经 + 褒义」，按结构盖。 */
  [/(很|真|挺|好)(棒|好|厉害|勇敢|坚强)|已经.{0,4}(很好|不错|够)|加油|不错啊|进步|坚持下去|继续保持|为你(高兴|骄傲)/, '夸或鼓励'],
  [/连续|第\s*[一二三四五六七八九十]\s*次|打卡|完成度/, '进度或计数'],
  /* 指令口吻 */
  [/建议你|你应该|你必须|正确的做法|最好的办法是/, '指令口吻'],
  /* 比喻。⚠️ 有标记的（像/一样/仿佛）好拦，无标记的拦不住——
     「不是松松土就能拔掉的野草」漏过一次。补一张具体物象的表：
     模型打比方时爱用的就那么几类东西，而这一层里出现它们几乎一定是比喻
     （产品的词表只有食物、身体和动作）。 */
  [/像.{0,6}一样|仿佛|如同|好比|似的/, '比喻'],
  [/野草|藤蔓|石头|大山|洪水|潮水|浪|漩涡|深渊|黑洞|牢笼|枷锁|绳子|茧|壳|雾|云|风筝|气球/, '打比方'],
  /* 括号里的自我说明——那是写字的痕迹，不是说话 */
  [/[（(][^）)]{0,30}[）)]/, '括号注解'],
  /* markdown。有些模型爱加星号和井号。
     ⚠️ 别拦 —— ：那是中文破折号，产品自己的 26 屏文案里到处在用。
        原来写 /—{2,}/ 把「又没忍住」——这是你心里冒出来的话吗 误杀了。
        markdown 的分割线是行首独占三个以上，拿这个特征区分。 */
  [/\*|(^|\n)\s*#|(^|\n)\s*[-—*]{3,}\s*(\n|$)/, 'markdown 标记'],
  /* 模型自曝身份，会把她从对话里踢出来 */
  [/作为一个|我是.{0,4}AI|语言模型|我不能提供|无法提供专业/, '模型自曝或免责'],
  /* ⚠️ 四个人不该有「我」。
     「我懂」「我听见了」会把它变成一个在共情你的实体——那正是 Tessa 那条线。
     四个人是四种看事情的角度，不是四个在场的朋友。 */
  /* ⚠️ 一律按「我＋感受/认知动词」拦，不要一个词一个词列——
     列词表漏过一次了：表里有「我知道你」，模型说的是「我知道」。 */
  [/我(懂|听见|明白|理解|知道|感受|在这|陪|替你|为你)/, '模型自称在共情'],
  /* 敬语。产品语气是坐在旁边的人，不是客服 */
  [/您/, '敬语'],
];

/* 结构要求 */
/* ⚠️ 下限只挡「等于没说」，不挡短。
   「肩膀松一下。」六个字是对的——地面本来就该说得最短。
   这个数原来写 8，会把正确的回答拦掉，而拦掉之后就退回模板，
   于是"太干"的问题反而是这条断言造成的。 */
const MIN = 4;
const MAX = 140;    // 太长就是在讲道理，而这一层不讲道理

function check(text) {
  const t = String(text || '').trim();
  if (!t) return '空';
  if (t.length < MIN) return '太短';
  if (t.length > MAX) return '太长';
  for (const [re, why] of HARD) if (re.test(t)) return why;
  /* 分点、小标题——那是文档不是说话 */
  if (/^[\s]*[-*•]|\n[\s]*[-*•]|第一[，,、]|首先[，,、]/.test(t)) return '分点';
  return null;   // null = 可以上屏
}

module.exports = { check, HARD, MIN, MAX };
