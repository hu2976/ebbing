CARDS.forEach((c) => {
  SCREENS[c.id] = { back: 'care-trans', body: () => {
    const b = [T('h', c.h), T('ti', '你会想'), T('p', c.think), T('ti', '真实是'), T('p', c.real)];
    if (c.realMore) b.push(T('s', c.realMore));
    if (c.key) b.push(T('box', c.key));
    b.push(T('ti', '现在'), T('p', c.now));
    if (c.nowMore) b.push(T('s', c.nowMore));
    /* 「必须动」是覆盖前面所有建议的例外条件——整屏在说「不下楼」，
       例外恰恰是「立刻下楼」。所以它走 warn 块：不折叠、完整显示。 */
    if (c.must) b.push(T('warn', c.must.replace(/^必须动：/, '')));
    return b;
  } };
});

