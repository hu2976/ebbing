function dayIndex() {
  const now = new Date();
  const today = new Date(now.getFullYear(), now.getMonth(), now.getDate());
  return Math.floor((today - new Date(2026, 0, 1)) / 864e5);
}

/* 按某一天取那天的滋味卡。书架上点哪一张就该展开哪一张——
   原来 taste-card 一律走 pick()（当日那条），所以点任何一格都是今天的。 */
function pickForDay(pool, day) {
  if (!Array.isArray(pool) || !pool.length) return null;
  if (!day) return pool[((dayIndex() % pool.length) + pool.length) % pool.length];
  const [y, m, d] = String(day).split('-').map(Number);
  const t = new Date(y, m - 1, d);
  const di = Math.floor((t - new Date(2026, 0, 1)) / 864e5);
  return pool[((di % pool.length) + pool.length) % pool.length];
}

function pick(pool) {
  if (!Array.isArray(pool) || !pool.length) return null;
  const i = ((dayIndex() % pool.length) + pool.length) % pool.length;
  return pool[i];
}

