/* 勾中的下标数组 → 组合键。空数组返回 null（调用处走"都没勾"那条路） */
function gateKey(picked) {
 const k = ['A', 'B', 'C'].filter((_, i) => picked.includes(i)).join('');
 return k || null;
}

