function dayKey(d) {
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

function agoToDate(ago) {
  const n = new Date();
  return dayKey(new Date(n.getFullYear(), n.getMonth(), n.getDate() - ago));
}

/* 某样食物别人写过的。旧的在前，和她自己那条时间线方向一致。
   ⚠️ 调用方必须先确认她已经写过（MINE.hasMine），这里不做这个判断——
   把「先写后看」放在调用点，读的时候才看得见那条规则。 */
function others(food) {
  const list = seed[food] || [];
  return list.map((x) => ({
    at: agoToDate(x.ago),
    cells: x.cells,
    text: Object.keys(x.cells).map((k) => x.cells[k]).join('。') + '。',
  })).sort((a, b) => (a.at < b.at ? -1 : 1));
}

function count(food) { return (seed[food] || []).length; }

module.exports = { others, count };
